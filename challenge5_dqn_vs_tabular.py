"""
challenge5_dqn_vs_tabular.py - CHALLENGE 5: Deep Q-Network vs tabular Q-Learning on LARGER boards.

DESIGN (choices of mine; the report says so)
  * Same game and rules as the main project (env.py): the agent chooses the dice, invalid move =
    stay + (-10), episode cut after 5*N rolls, default rewards.
  * Two new, larger boards with the same jump density as N100 (16 jump squares per 100 squares):
        N200: 16 ladders, 16 snakes      N400: 32 ladders, 32 snakes
    jump length 10..25, generated by challenge3_dynamic_board.generate_layout with a fixed id, so the
    layout is fully reproducible. Both obey the original rules (validate_board).
  * Algorithms: tabular Q-Learning (tabular.train, same alpha 0.1, gamma 0.99, epsilon 1.0 -> 0.05 over
    the first 70% of 2,000 episodes) and SB3 DQN (sb3_train.train_one, the SAME untuned hyperparameters
    as the main runs). DQN budget = 1,000 * N timesteps, the same rule used for N30/N50/N100.
  * Seeds: 10 for Q-Learning, 3 for DQN. Greedy evaluation for tabular uses 20 games per checkpoint
    (instead of 100) to keep the run short; games differ only by random tie-breaking.
  * Convergence: the main-project rule. A checkpoint is good if greedy success >= 95% and greedy rolls
    <= 1.10 * BFS minimum; converged at the first checkpoint from which every later one is good.
    Cost is reported in episodes AND environment steps (rolls), so the two algorithm families can be
    compared fairly, plus wall-clock time.
  * The N30/N50/N100 numbers in the summary are the ones already saved in results/ (main project);
    nothing is re-run for them.

Usage (pilot first):
  python challenge5_dqn_vs_tabular.py --boards N200 --q-seeds 0 --dqn-seeds 0 --dqn-scale 100 --workers 2
  python challenge5_dqn_vs_tabular.py --workers 6
Outputs: results_challenges/ch5_*  (per-run logs, runs table, summary table, plots, board layouts)
"""
