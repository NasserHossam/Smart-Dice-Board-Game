MAIN = ROOT / "results"

# --------------------------------------------------------------------------- larger boards
# layout ids were fixed once; the boards are registered at import so worker processes see them too.
LARGE_SPECS = {"N200": dict(layout_id=5200, n=200, k=16), "N400": dict(layout_id=5400, n=400, k=32)}


def make_large_board(name: str) -> Board:
    s = LARGE_SPECS[name]
    b = generate_layout(s["layout_id"], n=s["n"], k_ladders=s["k"], k_snakes=s["k"], lmin=10, lmax=25)
    return Board(name, b.n, dict(b.ladders), dict(b.snakes))


for _name in LARGE_SPECS:
    if _name not in BOARDS:
        BOARDS[_name] = make_large_board(_name)

GOOD = lambda s, m, bfs: (s >= 0.95) & (m <= 1.10 * bfs)  # noqa: E731


def discounted_optimum(board: Board, gamma: float = 0.99):
    """Policy with the best DISCOUNTED return (the objective the agents actually optimise), by value
    iteration on the known model. Returns (rolls it uses from square 1, its undiscounted return).
    On a large board this policy can take a ladder detour and use more rolls than the BFS minimum."""
    from env import DEFAULT_REWARDS as R
    n = board.n
    opts = {}
    for s in range(1, n):
        o = []
        for roll in range(1, 7):
            t = s + roll
            if t > n:
                o.append((R["invalid"], s))
                continue
            f = board.jump_map.get(t, t)
            r = (R["goal"] if f == n else R["ladder"] if t in board.ladders
                 else R["snake"] if t in board.snakes else R["normal"])
            o.append((r, f))
        opts[s] = o
    v = np.zeros(n + 1)
    for _ in range(100_000):
        new = v.copy()
        for s in range(1, n):
            new[s] = max(r + gamma * v[f] for r, f in opts[s])
        delta = np.max(np.abs(new - v))
        v = new
        if delta < 1e-10:
            break
    s, rolls, ret = 1, 0, 0.0
    while s != n and rolls < 5 * n:
        r, f = max(opts[s], key=lambda x: x[0] + gamma * v[x[1]])
        ret, s, rolls = ret + r, f, rolls + 1
    return rolls, ret


# --------------------------------------------------------------------------- one run (worker)
def run_qlearning(board: str, seed: int, episodes: int, eval_games: int, time_limit) -> dict:
    from tabular import train
    t0 = time.time()
    Q, log, summ = train(board, "qlearning", episodes, seed, eval_games=eval_games,
                         time_limit=time_limit, verbose=False)
    wall = time.time() - t0
    stem = f"ch5_qlearning_{board}_seed{seed}"
    log.to_csv(OUT / f"{stem}_log.csv", index=False)
    np.save(OUT / f"{stem}_Q.npy", Q)
    bfs = bfs_min_rolls(BOARDS[board])
    ev = log.dropna(subset=["eval_success"])
    ok = GOOD(ev.eval_success.to_numpy(), ev.eval_moves.to_numpy(), bfs)
    conv = stable_to_end(ev.episode.to_numpy(), ok)
    steps_cum = log.train_moves.cumsum().to_numpy()
    return {"board": board, "algo": "Q-Learning", "seed": seed, "bfs": bfs,
            "final_success": float(ev.eval_success.iloc[-1]), "final_rolls": float(ev.eval_moves.iloc[-1]),
            "final_return": float(ev.eval_return.iloc[-1]),
            "conv_episode": conv, "conv_steps": None if conv is None else int(steps_cum[conv - 1]),
            "episodes_run": int(len(log)), "steps_run": int(steps_cum[-1]), "wall_s": round(wall, 1),
            "stopped_by_time_limit": bool(summ["stopped_by_time_limit"])}


def run_dqn(board: str, seed: int, timesteps: int, time_limit) -> dict:
    from sb3_train import train_one
    t0 = time.time()
    s = train_one(board, "dqn", timesteps, seed, time_limit=time_limit, out_dir=OUT, tag="", verbose=False)
    wall = time.time() - t0
    # train_one names files sb3_dqn_<board>_seed<k>_*; rename to the ch5_ prefix
    for suffix in ("_episodes.csv", "_evals.csv", "_policy.npy", "_summary.json", "_model.zip"):
        src = OUT / f"{s['stem']}{suffix}"
        if src.exists():
            src.replace(OUT / f"ch5_{s['stem']}{suffix}")
    return {"board": board, "algo": "DQN", "seed": seed, "bfs": s["bfs_optimum"],
            "final_success": s["final_eval_success"], "final_rolls": s["final_eval_moves"],
            "final_return": s["final_eval_return"],
            "conv_episode": s["convergence_episode"], "conv_steps": s["convergence_timesteps"],
            "episodes_run": s["episodes_run"], "steps_run": s["timesteps_run"], "wall_s": round(wall, 1),
            "stopped_by_time_limit": bool(s["stopped_by_time_limit"])}


# --------------------------------------------------------------------------- self-test
def self_test():
    for name in LARGE_SPECS:
        b = BOARDS[name]
        validate_board(b)
        assert b == BOARDS[name] and make_large_board(name).ladders == b.ladders, "layout not reproducible"
        assert len(b.ladders) == len(b.snakes) == LARGE_SPECS[name]["k"]
        print(f"[ok] {name}: {len(b.ladders)} ladders, {len(b.snakes)} snakes, BFS min rolls {bfs_min_rolls(b)}, "
              f"best return {optimal_return(b):.0f}")
    # the main boards are untouched
    assert bfs_min_rolls(BOARDS["N100"]) == 10 and bfs_min_rolls(BOARDS["N30"]) == 4
    print("[ok] main boards unchanged")
    # on the main boards the best discounted-return policy is a BFS shortest path with the best return
    for name, best in (("N30", 139.0), ("N50", 159.0), ("N100", 196.0)):
        assert discounted_optimum(BOARDS[name]) == (bfs_min_rolls(BOARDS[name]), best), name
    for name in LARGE_SPECS:
        r, g = discounted_optimum(BOARDS[name])
        print(f"[ok] {name}: best discounted-return policy uses {r} rolls (BFS {bfs_min_rolls(BOARDS[name])}), "
              f"return {g:.0f}")
    print("[ok] discounted optimum = BFS path on N30/N50/N100")


# --------------------------------------------------------------------------- summary + plots
def main_project_rows() -> pd.DataFrame:
    """Q-Learning (seeds 0-19) and DQN (seeds 0-2) on N30/N50/N100 from the saved main results."""
    per_run = pd.read_csv(MAIN / "final_table_per_run.csv")
    per_run = per_run[per_run.algo.isin(["qlearning", "dqn"])].copy()
    rows = []
    for _, r in per_run.iterrows():
        conv = int(r.conv_episode) if pd.notna(r.conv_episode) else None
        if r.algo == "dqn":
            steps = r.conv_timesteps if pd.notna(r.conv_timesteps) else None
        else:   # tabular: environment steps = training rolls up to and including the convergence episode
            tag = "" if r.group == "main" else "_extra"
            log = pd.read_csv(MAIN / f"tabular_qlearning_{r.board}_seed{int(r.seed)}{tag}_log.csv")
            steps = None if conv is None else int(log.train_moves.iloc[:conv].sum())
        rows.append({"board": r.board, "algo": "Q-Learning" if r.algo == "qlearning" else "DQN", "seed": r.seed,
                     "bfs": int(r.bfs), "final_success": r.final_success, "final_rolls": r.final_moves,
                     "final_return": r.final_return, "conv_episode": conv, "conv_steps": steps,
                     "source": "main project"})
    return pd.DataFrame(rows)


def summarize(runs: pd.DataFrame) -> pd.DataFrame:
    out = []
    order = ["N30", "N50", "N100", "N200", "N400"]
    for board in order:
        for algo in ("Q-Learning", "DQN"):
            g = runs[(runs.board == board) & (runs.algo == algo)]
            if g.empty:
                continue
            conv = g.conv_episode.dropna().astype(float)
            steps = g.conv_steps.dropna().astype(float)
            d_rolls, d_ret = discounted_optimum(BOARDS[board])
            out.append({
                "board": board, "N": BOARDS[board].n, "algo": algo, "seeds": len(g),
                "BFS": int(bfs_min_rolls(BOARDS[board])), "best_return": round(optimal_return(BOARDS[board]), 1),
                "disc_opt_rolls": d_rolls, "disc_opt_return": d_ret,
                "share_matching_disc_opt_%": round(100 * float(((g.final_rolls == d_rolls)
                                                                & (np.abs(g.final_return - d_ret) < 1e-6)).mean()), 1),
                "success_%": round(100 * float((g.final_success >= 0.95).mean()), 1),
                "final_rolls_mean": round(float(g.final_rolls.mean()), 2),
                "final_rolls_sd": round(float(g.final_rolls.std(ddof=1)), 2) if len(g) > 1 else np.nan,
                "final_return_mean": round(float(g.final_return.mean()), 1),
                "conv_episodes_median": None if conv.empty else float(np.median(conv)),
                "conv_episodes_min": None if conv.empty else float(conv.min()),
                "conv_episodes_max": None if conv.empty else float(conv.max()),
                "conv_steps_median": None if steps.empty else float(np.median(steps)),
                "not_converged": int(g.conv_episode.isna().sum()),
                "wall_s_median": float(g.wall_s.median()) if "wall_s" in g and g.wall_s.notna().any() else np.nan,
            })
    return pd.DataFrame(out)


def _tab_curve(path: Path, bfs: int):
    log = pd.read_csv(path)
    steps = log.train_moves.cumsum().to_numpy()
    ev = log.dropna(subset=["eval_moves"])
    return steps[ev.episode.to_numpy() - 1], ev.eval_moves.to_numpy() / bfs


def _dqn_curve(path: Path, bfs: int):
    ev = pd.read_csv(path)
    return ev.timesteps.to_numpy(), ev.eval_moves.to_numpy() / bfs


def _median_curve(curves, grid):
    ys = [np.interp(grid, x, y, left=np.nan) for x, y in curves]
    return np.nanmedian(np.vstack(ys), axis=0)


def make_plots(summary: pd.DataFrame):
    # 1) cost to converge vs board size
    fig, ax = plt.subplots(1, 2, figsize=(12, 4.3))
    for algo, c in (("Q-Learning", "tab:blue"), ("DQN", "tab:green")):
        g = summary[summary.algo == algo]
        ax[0].plot(g.N, g.conv_steps_median, "o-", color=c, label=algo + (" (2,000 episodes)" if algo == "Q-Learning" else ""))
        ax[1].plot(g.N, g.conv_episodes_median, "o-", color=c, label=algo + (" (2,000 episodes)" if algo == "Q-Learning" else ""))
    for f in sorted(OUT.glob("ch5_budget_check_*ep.csv")):
        bc = pd.read_csv(f)
        med = bc.groupby("board")[["conv_steps", "conv_episode"]].median()
        ns = [BOARDS[b].n for b in med.index]
        lab = f"Q-Learning ({int(bc.episodes.iloc[0]):,} episodes)"
        ax[0].plot(ns, med.conv_steps, "s--", color="tab:cyan", label=lab)
        ax[1].plot(ns, med.conv_episode, "s--", color="tab:cyan", label=lab)
    from matplotlib.ticker import NullFormatter
    for a, t in zip(ax, ("environment steps to converge (median)", "training episodes to converge (median)")):
        a.set_xscale("log"); a.set_yscale("log"); a.set_xlabel("board size N (log)"); a.set_title(t)
        a.set_xticks([30, 50, 100, 200, 400]); a.set_xticklabels(["30", "50", "100", "200", "400"])
        a.xaxis.set_minor_formatter(NullFormatter())
        a.grid(alpha=0.3, which="both"); a.legend()
    fig.tight_layout(); fig.savefig(OUT / "ch5_cost_vs_board_size.png", dpi=130); plt.close(fig)

    # 2) learning curves on the large boards (greedy rolls / BFS vs environment steps)
    boards = [b for b in ("N100", "N200", "N400")]
    fig, axes = plt.subplots(1, len(boards), figsize=(5 * len(boards), 4.2))
    for a, board in zip(axes, boards):
        bfs = bfs_min_rolls(BOARDS[board])
        src_dir, prefix = (MAIN, "") if board == "N100" else (OUT, "ch5_")
        if board == "N100":
            tab = sorted(MAIN.glob(f"tabular_qlearning_{board}_seed*_log.csv"))
            tab = [p for p in tab if "pilot" not in p.name]
        else:
            tab = sorted(OUT.glob(f"ch5_qlearning_{board}_seed*_log.csv"))
        dqn = sorted(src_dir.glob(f"{prefix}sb3_dqn_{board}_seed*_evals.csv"))
        top = 1000 * BOARDS[board].n
        grid = np.logspace(2, np.log10(top), 300)
        for files, fn, c, lab in ((tab, _tab_curve, "tab:blue", "Q-Learning"), (dqn, _dqn_curve, "tab:green", "DQN")):
            if not files:
                continue
            curves = [fn(p, bfs) for p in files]
            a.plot(grid, _median_curve(curves, grid), color=c, label=f"{lab} (n={len(files)}, median)")
        a.axhline(1.0, ls="--", color="k", lw=1, label="BFS optimum")
        a.axhline(1.1, ls=":", color="gray", lw=1, label="convergence limit (1.10 x BFS)")
        a.set_xscale("log"); a.set_ylim(0, 6); a.set_xlabel("environment steps (log)")
        a.set_ylabel("greedy rolls / BFS minimum"); a.set_title(f"{board} (BFS {bfs})"); a.grid(alpha=0.3)
        a.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(OUT / "ch5_learning_curves_large.png", dpi=130); plt.close(fig)


# --------------------------------------------------------------------------- main
def main():
    p = argparse.ArgumentParser(description="Challenge 5: DQN vs tabular Q-Learning on larger boards")
    p.add_argument("--boards", nargs="+", default=list(LARGE_SPECS), choices=list(LARGE_SPECS))
    p.add_argument("--q-seeds", type=int, nargs="+", default=list(range(10)))
    p.add_argument("--dqn-seeds", type=int, nargs="+", default=[0, 1, 2])
    p.add_argument("--episodes", type=int, default=2000, help="tabular training episodes")
    p.add_argument("--eval-games", type=int, default=20)
    p.add_argument("--dqn-scale", type=int, default=1000, help="DQN timesteps = scale * N")
    p.add_argument("--workers", type=int, default=4)
    p.add_argument("--time-limit", type=float, default=None, help="max seconds PER run")
    p.add_argument("--summary-only", action="store_true", help="rebuild tables/plots from saved runs")
    p.add_argument("--budget-check", type=int, default=None, metavar="EPISODES",
                   help="only re-run Q-Learning with this many episodes (is the 2,000-episode budget the limit?)")
    a = p.parse_args()
    OUT.mkdir(exist_ok=True)

    self_test()
    if a.budget_check:
        from tabular import train
        rows = []
        for b in a.boards:
            bfs = bfs_min_rolls(BOARDS[b])
            d_rolls, _ = discounted_optimum(BOARDS[b])
            for s in a.q_seeds:
                _, log, _ = train(b, "qlearning", a.budget_check, s, eval_games=a.eval_games, verbose=False)
                ev = log.dropna(subset=["eval_success"])
                ok = GOOD(ev.eval_success.to_numpy(), ev.eval_moves.to_numpy(), bfs)
                conv = stable_to_end(ev.episode.to_numpy(), ok)
                rows.append({"board": b, "episodes": a.budget_check, "seed": s, "bfs": bfs, "disc_opt_rolls": d_rolls,
                             "final_rolls": float(ev.eval_moves.iloc[-1]),
                             "final_return": float(ev.eval_return.iloc[-1]), "conv_episode": conv,
                             "conv_steps": None if conv is None else int(log.train_moves.iloc[:conv].sum())})
                print(f"  budget check {b} seed{s}: final rolls {rows[-1]['final_rolls']:.0f}, converged at {conv}",
                      flush=True)
        df = pd.DataFrame(rows)
        df.to_csv(OUT / f"ch5_budget_check_{a.budget_check}ep.csv", index=False)
        print(df.groupby("board")[["final_rolls", "final_return"]].describe().round(2).to_string())
        return
    layouts = {n: {"n": BOARDS[n].n, "ladders": BOARDS[n].ladders, "snakes": BOARDS[n].snakes,
                   "bfs_min_rolls": bfs_min_rolls(BOARDS[n]), **LARGE_SPECS[n]} for n in LARGE_SPECS}
    (OUT / "ch5_boards.json").write_text(json.dumps(layouts, indent=1, default=int))

    runs_path = OUT / "ch5_runs.csv"
    if not a.summary_only:
        jobs = []
        with ProcessPoolExecutor(max_workers=a.workers) as ex:
            for b in a.boards:      # long DQN jobs first
                for s in a.dqn_seeds:
                    jobs.append(ex.submit(run_dqn, b, s, a.dqn_scale * BOARDS[b].n, a.time_limit))
            for b in a.boards:
                for s in a.q_seeds:
                    jobs.append(ex.submit(run_qlearning, b, s, a.episodes, a.eval_games, a.time_limit))
            rows = []
            for f in as_completed(jobs):
                r = f.result()
                rows.append(r)
                print(f"==> {r['algo']:<10} {r['board']} seed{r['seed']}: final rolls {r['final_rolls']:.0f} "
                      f"(BFS {r['bfs']}), converged at episode {r['conv_episode']} / step {r['conv_steps']}, "
                      f"{r['wall_s']}s", flush=True)
        new = pd.DataFrame(rows)
        if runs_path.exists():   # keep runs of other boards/seeds from earlier calls
            old = pd.read_csv(runs_path)
            key = ["board", "algo", "seed"]
            old = old.merge(new[key], on=key, how="left", indicator=True)
            old = old[old._merge == "left_only"].drop(columns="_merge")
            new = pd.concat([old, new], ignore_index=True)
        new.sort_values(["board", "algo", "seed"]).to_csv(runs_path, index=False)

    runs = pd.read_csv(runs_path)
    runs["source"] = "challenge 5"
    allruns = pd.concat([main_project_rows(), runs], ignore_index=True)
    summary = summarize(allruns)
    summary.to_csv(OUT / "ch5_summary.csv", index=False)
    make_plots(summary)
    with pd.option_context("display.width", 200, "display.max_columns", 30):
        print(summary.to_string(index=False))
    print("\nSaved: ch5_runs.csv, ch5_summary.csv, ch5_boards.json, ch5_cost_vs_board_size.png, "
          "ch5_learning_curves_large.png")


if __name__ == "__main__":
    main()
